/**
 * Official Veriko SDK for JavaScript and TypeScript.
 *
 * Veriko validates Mexican SPEI transfers against the CEP (Comprobante Electrónico de
 * Pago) that Banco de México issues, and returns a verdict.
 *
 * ```ts
 * import { Veriko, hasCep } from '@veriko-mx/sdk';
 *
 * const client = new Veriko(); // reads VERIKO_API_KEY from the environment
 *
 * const validation = await client.validateTransfer({
 *   sendDate: '2025-03-15',
 *   amount: 15000.5,
 *   trackingKey: 'MXBA20250315001234',
 *   beneficiaryAccount: '012180004412345678',
 * });
 *
 * if (hasCep(validation)) {
 *   const cep = await client.getCep(validation.id, { format: 'pdf' });
 *   await writeFile(cep.filename, cep.content);
 * }
 * ```
 *
 * API documentation: https://docs.veriko.mx
 */

